// 受限通道：香港个人档案经此读/写线上主页 publications（容器内 /data,/site，uid 1000）。
// stdin 第一行 verb：GET 返回现有数组；PUT 后跟新 pubs JSON 数组，按 DOI/标题 upsert
//   —— 已存在则用 incoming 的非空字段更新（可补图/改作者）；不存在则追加。
const fs = require("fs");
const DATA = "/data/publications.zh.json";
const SITE = "/site/publications-data.js";
const HEADER = "/* AUTO-GENERATED by UroExplorer admin. Edit via the admin panel, not by hand. */\n";
const norm = (d) => String(d || "").toLowerCase().replace(/^https?:\/\/(dx\.)?doi\.org\//, "").trim();
const normT = (s) => String(s || "").toLowerCase().replace(/[^a-z0-9一-龥]+/g, " ").replace(/\s+/g, " ").trim();
const input = fs.readFileSync(0, "utf-8");
const nl = input.indexOf("\n");
const verb = (nl < 0 ? input : input.slice(0, nl)).trim();
const body = nl < 0 ? "" : input.slice(nl + 1);
const arr = JSON.parse(fs.readFileSync(DATA, "utf-8"));
if (verb === "GET") { process.stdout.write(JSON.stringify(arr)); process.exit(0); }
if (verb === "PUT") {
  const incoming = JSON.parse(body);
  if (!Array.isArray(incoming)) { process.stderr.write("PUT body must be array"); process.exit(1); }
  let added = 0, updated = 0;
  for (const p of incoming) {
    const d = norm(p.doi);
    let idx = -1;
    if (d) idx = arr.findIndex((x) => norm(x.doi) === d);
    if (idx < 0 && p.title) idx = arr.findIndex((x) => normT(x.title) === normT(p.title));
    if (idx >= 0) {
      for (const [k, v] of Object.entries(p)) {
        if (v !== "" && v !== null && v !== undefined) arr[idx][k] = k === "doi" ? d : v;
      }
      updated++;
    } else {
      arr.push({ ...p, doi: d });
      added++;
    }
  }
  arr.sort((a, b) => Number(b.year) - Number(a.year));
  fs.writeFileSync(DATA, JSON.stringify(arr, null, 2));
  fs.writeFileSync(SITE, HEADER + "window.__PUBS__ = " + JSON.stringify(arr, null, 2) + ";\n");
  process.stdout.write(JSON.stringify({ added, updated, total: arr.length }));
  process.exit(0);
}
process.stderr.write("unknown verb"); process.exit(1);
